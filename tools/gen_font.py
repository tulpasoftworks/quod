"""Quod's text font, from a BDF: one bit a pixel, a byte a row (the left pixel the high bit), monospaced.

  gen_font.py [art/fonts/ter-u16n.bdf] [gen/quod_font.h]

The glyphs are Terminus Font's 8 x 16 (ter-u16n) by Dimitar Toshkov Zhekov, under the SIL Open Font License
(art/fonts/Terminus-OFL.txt); ASCII 32..126, the rest shows as '?'."""
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else 'art/fonts/ter-u16n.bdf'
OUT = sys.argv[2] if len(sys.argv) > 2 else 'gen/quod_font.h'
FIRST, LAST = 32, 126


def read_bdf(path):
    glyphs, ascent, box, cur = {}, None, None, None
    rows = None
    for line in open(path, encoding='latin-1'):
        w = line.split()
        if not w:
            continue
        if w[0] == 'FONTBOUNDINGBOX':
            box = tuple(int(v) for v in w[1:5])
        elif w[0] == 'FONT_ASCENT':
            ascent = int(w[1])
        elif w[0] == 'ENCODING':
            cur = {'code': int(w[1])}
        elif w[0] == 'BBX' and cur is not None:
            cur['bbx'] = tuple(int(v) for v in w[1:5])
        elif w[0] == 'BITMAP' and cur is not None:
            rows = []
        elif w[0] == 'ENDCHAR' and cur is not None:
            cur['rows'] = rows
            glyphs[cur['code']] = cur
            cur, rows = None, None
        elif rows is not None:
            rows.append(int(w[0], 16))
    return glyphs, ascent, box


def main():
    glyphs, ascent, (fw, fh, fx, fy) = read_bdf(SRC)
    if fw != 8:
        raise SystemExit(f'{SRC}: {fw} px wide; this format is 8')
    out = []
    for code in range(FIRST, LAST + 1):
        g = glyphs.get(code, glyphs[ord('?')])
        w, h, x, y = g['bbx']
        cell = [0] * fh
        top = ascent - (y + h)                  # the glyph's first row in the cell
        for i, bits in enumerate(g['rows']):
            nbytes = (w + 7) // 8
            v = bits >> (8 * nbytes - 8) if nbytes > 1 else bits   # (8 px: one byte)
            if 0 <= top + i < fh:
                cell[top + i] = (v >> x if x >= 0 else v << -x) & 0xFF
        out.append(cell)
    with open(OUT, 'w') as f:
        f.write('/* generated by tools/gen_font.py from art/fonts/ter-u16n.bdf: Terminus Font 8 x 16 by Dimitar Toshkov\n'
                ' * Zhekov (SIL Open Font License, art/fonts/Terminus-OFL.txt); ASCII %d..%d, a byte a row, left pixel high */\n'
                % (FIRST, LAST))
        f.write('static const uint8_t QFONT_S_ROWS[%d][%d] = {\n' % (len(out), fh))
        for code, cell in zip(range(FIRST, LAST + 1), out):
            f.write('    {%s},   /* %s */\n' % (', '.join('0x%02x' % v for v in cell),
                                                repr(chr(code)).replace('*/', '* /')))
        f.write('};\n')
        f.write('static const qfont_t QFONT_S = {%d, %d, %d, %d, &QFONT_S_ROWS[0][0]};\n' % (fh, 8, FIRST, LAST))
    print(OUT, len(out), 'glyphs')


main()
